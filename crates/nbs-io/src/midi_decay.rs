/// 包络在自身窗内线性插值取增益，`progress` 越界钳到端点（同 Miau `_value_at` 的取值口径）。
pub(super) fn gain_at(env: &[f32; 12], progress: f64) -> f64 {
    let scaled = progress.clamp(0.0, 1.0) * (env.len() - 1) as f64;
    let lo = scaled as usize;
    let hi = (lo + 1).min(env.len() - 1);
    let frac = scaled - lo as f64;
    f64::from(env[lo]) * (1.0 - frac) + f64::from(env[hi]) * frac
}
